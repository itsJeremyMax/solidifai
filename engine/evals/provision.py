"""Provision an eval workspace replicating the app's provisioner.

Mirrors the Claude-relevant subset of ``src-tauri/src/provision.rs``: the
instructional templates, the embedded skills tree, the ``solidifai-cad`` MCP
registration (including the app's ``"//"`` managed-marker key), the
pre-approval + SessionStart-hook settings, and the
``.solidifai/{artifacts,engine.sock}`` layout. The template AGENTS.md already
carries the default manufacturing-profile block, so it is copied verbatim
(the app re-renders that block from the live profile; evals run on defaults).
Skipped on purpose: the non-Claude harness configs (.codex/, opencode.json,
.cursor/, .opencode/skills) — evals drive Claude Code only.

One deliberate difference: the app's venv has the engine installed, while the
eval run may use the repo checkout directly, so the MCP env adds PYTHONPATH.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ENGINE_ROOT = Path(__file__).resolve().parents[1]
TEMPLATES_DIR = ENGINE_ROOT / "workspace_templates"
MCP_SERVER_NAME = "solidifai-cad"

# The app's marker comment for generated config files (provision.rs MANAGED_MARKER).
_MANAGED = "solidifai-managed: generated by solidifai; safe to overwrite"

# Verbatim copy of provision.rs USING_SOLIDIFAI_DIRECTIVE.
USING_SOLIDIFAI_DIRECTIVE = """\
solidifai CAD workspace: do this first.

Before you reply, take any action, or invoke any other skill, invoke the \
`using-solidifai` skill. It orients you to this workspace and the `solidifai-cad` \
engine that every other solidifai skill drives. This holds even when the request \
looks simple or maps cleanly to modeling or product design: those skills assume \
you have already read using-solidifai.

If your harness has no skill mechanism, read \
`.claude/skills/using-solidifai/SKILL.md` first instead, then continue.
"""


def _hook_command(py: str, directive_path: str) -> str:
    """Mirror provision.rs session_start_hook_command(): print the directive
    file (passed as argv[1]) so the harness injects it at session start."""
    return (
        f'"{py}" -c "import pathlib,sys; '
        "sys.stdout.write(pathlib.Path(sys.argv[1]).read_text(encoding='utf-8'))\" "
        f'"{directive_path}"'
    )


def mcp_config(engine_python: str, sock_path: str) -> dict:
    return {
        "//": _MANAGED,
        "mcpServers": {
            MCP_SERVER_NAME: {
                "command": engine_python,
                "args": ["-m", "solidifai_mcp"],
                "env": {
                    "SOLIDIFAI_ENGINE_SOCK": sock_path,
                    "PYTHONPATH": str(ENGINE_ROOT),
                },
            }
        },
    }


def claude_settings(engine_python: str, directive_path: str) -> dict:
    return {
        "//": _MANAGED,
        "enabledMcpjsonServers": [MCP_SERVER_NAME],
        "hooks": {
            "SessionStart": [
                {
                    "hooks": [
                        {
                            "type": "command",
                            "command": _hook_command(engine_python, directive_path),
                        }
                    ]
                }
            ]
        },
    }


def provision_workspace(root: str | Path, engine_python: str) -> Path:
    """Write a fresh (or refresh an existing) eval workspace at ``root``.
    Returns ``root``. Idempotent: every file here is harness-owned."""
    root = Path(root)
    dot = root / ".solidifai"
    (dot / "artifacts").mkdir(parents=True, exist_ok=True)
    sock = dot / "engine.sock"

    shutil.copyfile(TEMPLATES_DIR / "AGENTS.md", root / "AGENTS.md")
    shutil.copyfile(TEMPLATES_DIR / "CLAUDE.md", root / "CLAUDE.md")

    # Mirror provision.rs write_skills_tree: drop skill dirs no longer in the
    # template set (copytree only adds/overwrites), then write the current set.
    skills_dest = root / ".claude" / "skills"
    template_skills = {p.name for p in (TEMPLATES_DIR / "skills").iterdir() if p.is_dir()}
    if skills_dest.is_dir():
        for existing in skills_dest.iterdir():
            if existing.is_dir() and existing.name not in template_skills:
                shutil.rmtree(existing)
    shutil.copytree(TEMPLATES_DIR / "skills", skills_dest, dirs_exist_ok=True)

    directive = dot / "using-solidifai-directive.md"
    directive.write_text(USING_SOLIDIFAI_DIRECTIVE, encoding="utf-8")

    (root / ".mcp.json").write_text(
        json.dumps(mcp_config(engine_python, str(sock)), indent=2) + "\n", encoding="utf-8"
    )
    (root / ".claude" / "settings.json").write_text(
        json.dumps(claude_settings(engine_python, str(directive)), indent=2) + "\n",
        encoding="utf-8",
    )
    return root
